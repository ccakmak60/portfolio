function setLine(face: Face, text: string) {
    const lamps: [number, number][] = [];
    let x = 0;
    for (const ch of text) {
        if (ch === " ") {
            x += face.space + face.gap;
            continue;
        }
        const glyph = face.glyphs[ch];
        if (!glyph)
            throw new Error(`No glyph for "${ch}"`);
        glyph.forEach((row, y) => {
            for (let c = 0; c < row.length; c++)
                if (row[c] === "#")
                    lamps.push([x + c, y]);
        });
        x += glyph[0].length + face.gap;
    }
    return { lamps, width: Math.max(0, x - face.gap) };
}

